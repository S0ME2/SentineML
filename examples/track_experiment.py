"""Record three synthetic experiments against a SentinelML server."""

import argparse
import os
import uuid

from sentinelml_client import SentinelMLClient


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--url",
        default=os.getenv("SENTINELML_URL", "http://127.0.0.1:8888"),
        help="SentinelML base URL (default: SENTINELML_URL or localhost)",
    )
    args = parser.parse_args()
    suffix = uuid.uuid4().hex[:8]
    client = SentinelMLClient(args.url)
    project = client.create_project(
        f"synthetic-baseline-{suffix}", "Dependency-free example"
    )
    dataset = client.create_dataset(
        f"synthetic-regression-{suffix}",
        "v1",
        source="examples/track_experiment.py",
        metadata="synthetic data; no external dataset; generated by demo",
    )
    model = client.create_model(f"mean-predictor-{suffix}", "v1", model_type="baseline")
    client.ensure_metric_direction("mae", maximize=False)

    targets = [index / 10 for index in range(10)]
    for bias in (0.0, 0.15, -0.1):
        run = client.create_run(
            project["id"],
            dataset["id"],
            model["id"],
            notes="Synthetic demo; metric computed from generated targets",
        )
        client.add_parameter(run["id"], "sample_count", len(targets), value_type="int")
        client.add_parameter(run["id"], "prediction_bias", bias, value_type="float")
        client.add_parameter(
            run["id"], "provenance", "manual synthetic example", value_type="str"
        )
        predictions = [target + bias for target in targets]
        mae = sum(
            abs(target - prediction)
            for target, prediction in zip(targets, predictions, strict=True)
        ) / len(targets)
        with client.experiment_run(run["id"]) as active_run:
            active_run.log_metric("mae", mae)
        print(f"Completed run {run['id']} bias={bias} mae={mae:.4f}")

    print(f"Completed 3 synthetic SentinelML runs in project {project['name']}")


if __name__ == "__main__":
    main()
